//! audiod: Vanta Audio Stream Mixer and Playback daemon.

#![no_std]
#![no_main]

// 440 Hz sine wave PCM buffer (16-bit stereo)
static SINE_WAVE: [u8; 128] = [
    0x00, 0x00, 0x00, 0x00, 0x40, 0x10, 0x40, 0x10,
    0x80, 0x20, 0x80, 0x20, 0xb0, 0x30, 0xb0, 0x30,
    0x00, 0x40, 0x00, 0x40, 0xb0, 0x30, 0xb0, 0x30,
    0x80, 0x20, 0x80, 0x20, 0x40, 0x10, 0x40, 0x10,
    0x00, 0x00, 0x00, 0x00, 0xc0, 0xef, 0xc0, 0xef,
    0x80, 0xdf, 0x80, 0xdf, 0x50, 0xcf, 0x50, 0xcf,
    0x00, 0xc0, 0x00, 0xc0, 0x50, 0xcf, 0x50, 0xcf,
    0x80, 0xdf, 0x80, 0xdf, 0xc0, 0xef, 0xc0, 0xef,
    0x00, 0x00, 0x00, 0x00, 0x40, 0x10, 0x40, 0x10,
    0x80, 0x20, 0x80, 0x20, 0xb0, 0x30, 0xb0, 0x30,
    0x00, 0x40, 0x00, 0x40, 0xb0, 0x30, 0xb0, 0x30,
    0x80, 0x20, 0x80, 0x20, 0x40, 0x10, 0x40, 0x10,
    0x00, 0x00, 0x00, 0x00, 0xc0, 0xef, 0xc0, 0xef,
    0x80, 0xdf, 0x80, 0xdf, 0x50, 0xcf, 0x50, 0xcf,
    0x00, 0xc0, 0x00, 0xc0, 0x50, 0xcf, 0x50, 0xcf,
    0x80, 0xdf, 0x80, 0xdf, 0xc0, 0xef, 0xc0, 0xef,
];

#[no_mangle]
pub extern "C" fn _start() -> ! {
    let res = vanta_userland::audio_play(&SINE_WAVE);
    if res == u64::MAX - 1 {
        vanta_userland::exit(1);
    }
    vanta_userland::write(1, b"audiod: PCM audio stream playback verified\n");
    vanta_userland::exit(0);
}
